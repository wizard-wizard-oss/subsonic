// Mosaïque commune, route dédiée, lecture, pagination et conservation de la page après un ajout.
const assert = require("node:assert/strict"), fs = require("node:fs"), path = require("node:path"), vm = require("node:vm");
const {JSDOM} = require(process.argv[2] || "jsdom");
const root = path.join(__dirname, "../src/web-pc");
const dom = new JSDOM(fs.readFileSync(path.join(root, "index.html"), "utf8"), {url:"https://music.example/",runScripts:"outside-only"});
const d = dom.window.document, run = code => vm.runInContext(code, dom.getInternalVMContext());
const load = name => run(fs.readFileSync(path.join(root, "static/js/" + name + ".js"), "utf8"));
const settle = () => new Promise(resolve => setTimeout(resolve, 400));
(async () => { try {
  load("core"); load("icons");
  run(`App.user={id:1,roles:["stream","playlist"]};App.preferences={};
    App.texts={"playlist.tab":"Playlists","playlist.see_all":"Tout voir ›","playlist.sort_name":"Nom","playlist.sort_recent":"Modification récente"};
    window.calls=[];window.played=[];window.drops=[];window.route={view:"playlists"};
    window.cards=[{id:"1",name:"<Été>",owner:"alice",mine:true,songCount:4,duration:60,coverIds:["a","b","c","d"]},
      {id:"2",name:"Vide",owner:"bob",mine:false,community:true,songCount:0,coverIds:[]}];
    App.player={playList:(songs)=>played.push(songs)};App.live={on:()=>()=>{}};
    const Dialogs={};const ExtMusic={favoritesReady:async()=>{}};
    const Dnd={target:(node,allowed,drop)=>drops.push({node,allowed,drop})};
    App.api.get=async(url,params)=>{calls.push({url,params});if(url==="/api/playlist")return {...cards[0],songs:[{id:"song"}]};
      return {playlists:params.page?[cards[1]]:[cards[0]],hasMore:!params.page,sorts:["name","recent"],sort:"name"};};`);
  load("views"); load("playlists"); load("playlist-artwork"); load("playlist-card"); load("playlist-gallery");
  await run('Views.playlists.render(document.getElementById("main"),route)');
  const main = d.getElementById("main"), first = main.querySelector(".playlist-card");
  assert.ok(first); assert.equal(first.querySelectorAll(".playlist-artwork img").length,4);
  assert.equal(first.querySelector(".playlist-card-name").textContent,"<Été>");
  assert.equal(first.querySelector(".playlist-card-name").children.length,0);
  assert.equal(first.querySelector("a").getAttribute("href"),"#/playlist/1");
  first.querySelector(".playlist-card-play").click(); await settle();
  assert.equal(run('played[0][0].id'),"song");
  main.querySelector(".playlist-gallery-more").click(); await settle();
  assert.equal(main.querySelectorAll(".playlist-card").length,2);
  assert.equal(main.querySelector(".playlist-card"),first);
  assert.equal(main.querySelectorAll(".playlist-card")[1].querySelector("button"),null);
  const search=main.querySelector('input[type="search"]'), sort=main.querySelector("select");
  main.scrollTop=123;
  run('cards[0].songCount=5;App.bus.emit("playlists",cards);App.bus.emit("playlist-changed","1")'); await settle();
  assert.equal(main.querySelector("input"),search); assert.equal(main.querySelector("select"),sort);
  assert.equal(main.querySelectorAll(".playlist-card").length,2); assert.equal(main.scrollTop,123);
  assert.equal(main.querySelectorAll(".playlist-card")[1].dataset.id,"2");
  run('window.originalGet=App.api.get;window.rejectNext=true;App.api.get=async(url,params)=>{if(rejectNext){rejectNext=false;throw new ApiError(503,"subsonic.unreachable");}return originalGet(url,params);};');
  search.value="Été"; search.dispatchEvent(new dom.window.Event("input")); await settle();
  const retry=[...main.querySelectorAll("button")].find(button=>button.textContent==="nav.artists_retry");
  assert.equal(retry.hidden,false);
  retry.click(); await settle();
  assert.equal(run('calls.at(-1).params.page'),0,"réessayer un filtre reprend sa première page");
  assert.equal(run('calls.at(-1).params.q'),"Été");
  run('Views.playlists.destroy();window.route={view:"playlist",id:"1"};Views.songTable=()=>App.el("div.songs");');
  await run('Views.playlist.render(document.getElementById("main"),route)');
  assert.equal(main.querySelectorAll(".playlist-artwork img").length,4);
  run('Views.playlist.destroy()');
  load("desktop-navigation");run('App.translate();App.music={route:{view:"playlists"}};window.desktop=new DesktopNavigation()');
  assert.ok(d.querySelector('.desktop-playlist-heading a[href="#/playlists"]'));
  assert.equal(d.querySelector('.desktop-playlist-heading .playlist-see-all').textContent,"Tout voir ›");
  run('desktop.destroy()');
  assert.ok(d.querySelector('#panel-playlists .playlist-see-all[href="#/playlists"]'));
  load("app"); assert.equal(run('MusicApp.parse("#/playlists").view'),"playlists");
  dom.window.close();console.log("OK galerie playlists : mosaïques, navigation, lecture et pagination locale");
} catch(error) {console.error(error);dom.window.close();process.exitCode=1;} })();
